using System.Linq;
using Jellyfin.Plugin.ThemeForge.Engines.Scoring.Rules;
using Xunit;

namespace Jellyfin.Plugin.ThemeForge.Tests;

/// <summary>
/// Pins the veto on music a generator made: the uploads that were being assigned as themes, and
/// the ordinary titles that merely contain the letters.
/// </summary>
public sealed class AiGeneratedRuleTests
{
    private readonly AiGeneratedRule _rule = new();

    [Theory]
    [InlineData("Lucky Strike – Official Theme Song (AI Generated)")]
    [InlineData("Lucky Strike Theme Song [AI]")]
    [InlineData("Lucky Strike - Main Theme | A.I. Music")]
    [InlineData("Lucky Strike Theme (AI Cover)")]
    [InlineData("Lucky Strike theme song ai-generated")]
    [InlineData("Lucky Strike Theme Song (made with AI)")]
    [InlineData("Lucky Strike Theme Song [Suno AI]")]
    [InlineData("Lucky Strike Theme - Suno v4")]
    [InlineData("Lucky Strike Theme (created using artificial intelligence)")]
    [InlineData("Lucky Strike Theme #suno")]
    [InlineData("Lucky Strike Theme | Udio AI")]
    public void VetoesATitleThatSaysItWasGenerated(string title)
    {
        var verdict = _rule.Evaluate(TestData.Candidate(title), TestData.Context(TestData.Movie("Lucky Strike", 2026)));

        Assert.True(verdict.IsVeto, title);
    }

    [Theory]
    [InlineData("Epic AI Music")]
    [InlineData("AI Soundtracks")]
    [InlineData("Suno AI Covers")]
    public void VetoesAChannelThatSaysItGenerates(string channel)
    {
        var candidate = TestData.Candidate("Lucky Strike Main Theme", channel: channel);

        Assert.True(_rule.Evaluate(candidate, TestData.Context(TestData.Movie("Lucky Strike", 2026))).IsVeto);
    }

    [Theory]
    [InlineData("Made with Suno v4. Lyrics by me.")]
    [InlineData("Theme song for the film. #aimusic #lucky")]
    [InlineData("This track was generated by AI from the film's synopsis.")]
    public void VetoesADescriptionThatSaysItWasGenerated(string description)
    {
        var candidate = TestData.Candidate("Lucky Strike Main Theme") with { Description = description };

        Assert.True(_rule.Evaluate(candidate, TestData.Context(TestData.Movie("Lucky Strike", 2026))).IsVeto);
    }

    [Theory]
    [InlineData("Ai no Uta (Opening Theme)")] // Japanese for "song of love", and not in capitals.
    [InlineData("Hawaii Five-O Theme")]
    [InlineData("Daisuke - Opening")]
    [InlineData("Suno Na Sangemarmar - Main Theme")] // "Suno" is everyday Hindi.
    [InlineData("Air on the G String")]
    [InlineData("MAIN TITLE - Alien (1979)")]
    [InlineData("Fight Club Main Theme - The Dust Brothers")]
    public void LeavesOrdinaryTitlesAlone(string title)
    {
        var verdict = _rule.Evaluate(TestData.Candidate(title), TestData.Context(TestData.Movie("Whatever", 2001)));

        Assert.False(verdict.IsVeto, title);
    }

    [Fact]
    public void LeavesAloneAWorkWhoseOwnTitleHasTheLetters()
    {
        // Spielberg's film: its theme's uploads are titled with its name.
        var film = TestData.Movie("A.I. Artificial Intelligence", 2001, composers: new[] { "John Williams" });
        var candidate = TestData.Candidate("A.I. Artificial Intelligence - Main Theme (John Williams)");

        Assert.False(_rule.Evaluate(candidate, TestData.Context(film)).IsVeto);
    }

    [Fact]
    public void StillVetoesAGeneratedUploadForAWorkWhoseTitleHasTheLetters()
    {
        var film = TestData.Movie("A.I. Artificial Intelligence", 2001);
        var candidate = TestData.Candidate("A.I. Artificial Intelligence Theme Song (AI Generated)");

        Assert.True(_rule.Evaluate(candidate, TestData.Context(film)).IsVeto);
    }

    [Theory]
    [InlineData("Original recording. Not AI generated.")]
    [InlineData("No AI music here, this is the real score.")]
    [InlineData("Performed live, without AI vocals.")]
    public void ADescriptionDenyingItDoesNotCountAgainstIt(string description)
    {
        var candidate = TestData.Candidate("Lucky Strike Main Theme") with { Description = description };

        Assert.False(_rule.Evaluate(candidate, TestData.Context(TestData.Movie("Lucky Strike", 2026))).IsVeto);
    }

    [Fact]
    public void ADescriptionMentioningTheLettersAloneDoesNotCount()
    {
        // Only a phrase counts in a description; "AI" on its own there is far too common.
        var candidate = TestData.Candidate("Lucky Strike Main Theme") with { Description = "Music by Larry Groupé. AI subtitles available." };

        Assert.False(_rule.Evaluate(candidate, TestData.Context(TestData.Movie("Lucky Strike", 2026))).IsVeto);
    }

    [Fact]
    public void TheFullEngineNeverRanksAGeneratedThemeAboveNothing()
    {
        // The exact shape that was assigned: names the film exactly, calls itself its official
        // theme song, and was made by a generator.
        var film = TestData.Movie("Lucky Strike", 2026, composers: new[] { "Larry Groupé" });
        var generated = TestData.Candidate("Lucky Strike – Official Theme Song (AI Generated)", duration: 150, views: 900);
        var real = TestData.Candidate("Lucky Strike - Main Theme - Larry Groupé", duration: 140, views: 900);

        var ranked = TestData.Engine().Rank(new[] { generated, real }, TestData.Context(film));

        Assert.True(ranked.Single(result => result.Candidate == generated).IsVetoed);
        Assert.Same(real, ranked[0].Candidate);
    }

    [Fact]
    public void SaysWhatGaveItAway()
    {
        var verdict = _rule.Evaluate(
            TestData.Candidate("Lucky Strike Theme Song [Suno AI]"),
            TestData.Context(TestData.Movie("Lucky Strike", 2026)));

        Assert.Contains("Suno AI", verdict.Reason, System.StringComparison.Ordinal);
    }
}
